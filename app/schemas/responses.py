"""
API Response Schemas
Matches the output payload generated by the VerificationService.
"""
from typing import List, Dict, Any
from pydantic import BaseModel, Field

class Breakdown(BaseModel):
    True_count: int = Field(alias="True")
    False_count: int = Field(alias="False")
    Unverified_count: int = Field(alias="Unverified")

class Summary(BaseModel):
    # FIXED TYPO: Spelled with an 'i' to exactly match the backend dict key
    credibility_score: float
    rating: str
    total_claims_checked: int
    breakdown: Breakdown
    total_unique_sources_cited: int
    verdict_justification: str
    sourcing_traces: Dict[str, str]

class DetailedAudit(BaseModel):
    claim: str
    verdict: str
    explanation: str
    sources: List[str]

class AuditResponse(BaseModel):
    summary: Summary
    # Note: If you encounter a validation error on this key next, change this 
    # key name to match exactly whatever list key your VerificationService output uses 
    # (e.g., detailed_audits, verified_claims, or claims)
    detailed_audits: List[DetailedAudit]